"""Бонусные баллы: курс балла и перевод баллов в деньги.

В колонке ``users.bonus_points_kopeks`` лежит **денежная стоимость** баллов в
копейках, а не их количество. Так списание и проверки «хватает ли» считаются
как обычные деньги — без пересчётов на каждом шаге прораты и процента скидки
(см. ``subtract_user_balance`` и ``User.available_balance_kopeks``).

Поэтому курс нужен только на границе с человеком: оператор вводит количество
баллов, человек видит количество баллов, а внутри всё в копейках. Курс задан
здесь одной константой — больше нигде умножать на 100 или на 50 нельзя.

Курс: **1 балл = 0,5 ₽** (решение владельца, 26.11.2026). Половина рубля —
целое число копеек, поэтому нечётное количество баллов считается точно:
49 баллов = 2450 копеек = 24,5 ₽.
"""

from __future__ import annotations

from app.config import settings


#: Сколько копеек стоит один балл.
BONUS_POINT_VALUE_KOPEKS = 50


def points_to_kopeks(points: float) -> int:
    """Количество баллов (от оператора) → денежная стоимость в копейках."""
    return int(round(points * BONUS_POINT_VALUE_KOPEKS))


def kopeks_to_points(kopeks: int | None) -> float:
    """Денежная стоимость в копейках → количество баллов."""
    return (kopeks or 0) / BONUS_POINT_VALUE_KOPEKS


def format_bonus_points(kopeks: int | None) -> str:
    """Бонусные баллы числом: «500», «12.5».

    Слово «баллов» стоит в шаблонах ПЕРЕД числом («Всего баллов: 500»),
    поэтому склонять ничего не нужно — и в остальных локалях слово своё.
    Дробная часть появляется после частичной оплаты (баллы уходят копейками
    своей стоимости), поэтому ноль в хвосте убираем.
    """
    value = kopeks_to_points(kopeks)
    if value == int(value):
        return str(int(value))
    return f'{value:.2f}'.rstrip('0').rstrip('.')


def format_bonus_points_with_value(kopeks: int | None) -> str:
    """Баллы и их стоимость: «49 (24.5 ₽)».

    Курс не единица, поэтому одно число ввело бы человека в заблуждение: 100
    баллов — это 50 ₽ скидки, а не 100. Стоимость печатаем без округления
    копеек (``round_kopeks=False``): при включённом ``PRICE_ROUNDING_ENABLED``
    те самые 24,5 ₽ показались бы как «24 ₽».

    Подставляется в существующий ``{points}`` локалей — так строка остаётся
    одной подстановкой и ни один ключ локалей менять не пришлось.
    """
    return f'{format_bonus_points(kopeks)} ({settings.format_price(kopeks or 0, round_kopeks=False)})'
